// Build the receiver demo: one self-contained index.html + transcript.txt (the text fallback), from committed data only.
// node build.mjs <repo_root> <out_dir>
import fs from 'fs'; import path from 'path'; import crypto from 'crypto';
import * as esbuild from 'esbuild';
import { blake3 } from '@noble/hashes/blake3';
import { ed25519 } from '@noble/curves/ed25519';
import * as V from './verify.mjs';
const [, , ROOT = '/home/user/esa_poster', OUT = '../site'] = process.argv;
const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(here, OUT); fs.mkdirSync(out, { recursive: true });
const bundlePath = path.join(ROOT, 'research/repro/v8/proof_bundle_ndvi.cbor');
const bundleBytes = new Uint8Array(fs.readFileSync(bundlePath));
const sha = crypto.createHash('sha256').update(bundleBytes).digest('hex');
const win = JSON.parse(fs.readFileSync(path.join(ROOT, 'research/repro/data/v8/pixel_windows.json'), 'utf8'));
const wkey = Object.keys(win).find((k) => k.startsWith('oj5cecci')); const w = win[wkey];
const img = fs.readFileSync(path.join(here, '../keylong_tc_192.webp')).toString('base64');

// ---- the same receiver, run here, writes the transcript and asserts the expected verdicts
const bundle = V.cbor(bundleBytes);
const edVerify = (s, m, p) => { try { return ed25519.verify(s, m, p); } catch { return false; } };
const receive = V.makeReceiver({ blake3, edVerify, bundle });
const tok = V.parseToken(bundle.token);
const fact = V.factsRaw(V.bytesOf(bundle.entry)).find((x) => V.b32e(blake3(x)) === tok.cid);
const M = V.mutations(fact, bundle.token), rec = V.cbor(fact), m8cid = V.b32e(blake3(M.m8));
const cases = [
  ['prose', 'A paraphrase', '"NDVI is about 0.47 at the Keylong field, late September."', { kind: 'prose' }, 'ACCEPTED'],
  ['M3', 'One byte changed in transit (value +1 ULP, token kept)', `byte ${M.off + 7}: 0x${fact[M.off + 7].toString(16)} -> 0x${M.m3[M.off + 7].toString(16)} (value 0.4708994708994709 -> 0.47089947089947093)`, { kind: 'ref', token: bundle.token, bytes: M.m3 }, 'REFUSED'],
  ['M4', 'The right record, cited for another place', `emem:fact:${M.otherCell}:${tok.cid}`, { kind: 'ref', token: `emem:fact:${M.otherCell}:${tok.cid}`, bytes: fact }, 'REFUSED'],
  ['M8', 'Value forged to 0.45 and re-hashed', `emem:fact:${tok.cell}:${m8cid}`, { kind: 'ref', token: `emem:fact:${tok.cell}:${m8cid}`, bytes: M.m8 }, 'REFUSED'],
  ['G0', 'The genuine handoff', bundle.token, { kind: 'ref', token: bundle.token, bytes: fact }, 'ACCEPTED'],
];
const L = [];
L.push('EMEM receiver demo: text version (deterministic; generated by build.mjs from committed data)');
L.push(`Observation: NDVI ${rec.value} at cell ${rec.cell} (near Keylong, Lahaul, India), Sentinel-2A L2A B08/B04, captured ${rec.sources[0].captured_at}, signed ${rec.signed_at}.`);
L.push(`Agent A hands over: ${bundle.token}`);
L.push(`It names ${fact.length} bytes of CBOR by their BLAKE3-256 hash. Receiver: Agent B, using BLAKE3, Ed25519 and CBOR only; pinned key ${V.PINNED_KEY_B32}.`);
L.push('');
for (const [id, title, got, h, expect] of cases) {
  const r = receive(h);
  if (r.verdict !== expect) throw new Error(`${id}: expected ${expect}, got ${r.verdict}`);
  L.push(`${id}. ${title}`); L.push(`   B receives: ${got}`);
  for (const s of r.steps) L.push(`   [${s.ok === null ? ' ' : s.ok ? 'pass' : 'FAIL'}] ${s.layer} ${s.text}`);
  L.push(`   => ${r.verdict === 'REFUSED' ? 'REFUSED' : r.checked ? 'ACCEPTED, checked' : 'ACCEPTED, unchecked'}: ${r.why}`); L.push('');
}
const n = (dn) => V.ndvi(dn[0], dn[1], w.offset);
L.push('L3. Re-read the named pixel (live in the browser; committed copy below)');
L.push(`   files: ${bundle.upstream.map((u) => u.url.split('/').pop()).join(', ')}; pixel col ${bundle.upstream[0].col}, row ${bundle.upstream[0].row}`);
L.push(`   named pixel: B08 ${w.B08[2][2]}, B04 ${w.B04[2][2]}, offset ${w.offset} -> NDVI ${n([w.B08[2][2], w.B04[2][2]])} (signed value ${rec.value})`);
L.push(`   pixel 10 m south: B08 ${w.B08[3][2]}, B04 ${w.B04[3][2]} -> NDVI ${n([w.B08[3][2], w.B04[3][2]])}. Before 28 Sep 2026 emem's reader took this pixel; 162 of 200 sampled earlier records carried such values. Signatures cannot see it; only the re-read can.`);
L.push('');
L.push('Not checkable here: L4 whether this cell is the field Agent A meant; L5 whether the sensor and a decision taken on the value are right.');
L.push('A signature fixes the bytes. It does not make the measurement true.');
L.push(''); L.push(`Embedded data: research/repro/v8/proof_bundle_ndvi.cbor (${bundleBytes.length} B, sha256 ${sha}); research/repro/data/v8/pixel_windows.json ["${wkey}"].`);
fs.writeFileSync(path.join(out, 'transcript.txt'), L.join('\n') + '\n');

// ---- the page
const js = await esbuild.build({ entryPoints: [path.join(here, 'page.js')], bundle: true, minify: true, format: 'iife', target: ['es2020', 'safari15'], write: false });
const DATA = JSON.stringify({ bundle_b64: Buffer.from(bundleBytes).toString('base64'), window_oj5: { B08: w.B08, B04: w.B04, offset: w.offset } });
let html = fs.readFileSync(path.join(here, 'template.html'), 'utf8')
  .replace('{{IMG}}', 'data:image/webp;base64,' + img).replace('{{DATA}}', () => DATA).replace('{{BUNDLE_JS}}', () => js.outputFiles[0].text.replace(/<\/script/g, '<\\/script'))
  .replace('{{TOKEN_Q}}', encodeURIComponent(bundle.token)).replace('{{BUNDLE_LEN}}', bundleBytes.length.toLocaleString('en')).replace('{{BUNDLE_SHA}}', sha);
fs.writeFileSync(path.join(out, 'index.html'), html);
const h = (f) => crypto.createHash('sha256').update(fs.readFileSync(path.join(out, f))).digest('hex');
console.log(JSON.stringify({ out, index_bytes: html.length, js_bytes: js.outputFiles[0].text.length, index_sha256: h('index.html'), transcript_sha256: h('transcript.txt') }));
